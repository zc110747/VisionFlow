"""Write tests/golden/palm_anchors_reference.txt from the official literal.

The anchor table is the single highest-risk piece of the hand branch: the palm
model does not embed it, so the runtime must generate the same 2016 rows in the
same order, and getting it wrong silently produces garbage boxes instead of an
error. This script transcribes the OFFICIAL opencv_zoo literal verbatim (it does
NOT regenerate it from the 2-layer formula - that would make the comparison
circular and unable to catch a wrong formula).

Usage: make_palm_anchor_reference.py <mp_palmdet.py> <out.txt>
"""
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
src = open(src_path, encoding="utf-8").read()

m = re.search(r"def _load_anchors\(self\):\s*return np\.array\((\[.*?\])\s*,"
              r"\s*dtype=np\.float32\)", src, re.S)
if not m:
    raise SystemExit("could not find the _load_anchors() literal in " + src_path)

nums = re.findall(r"-?\d+\.\d+(?:e-?\d+)?", m.group(1))
if len(nums) != 2016 * 2:
    raise SystemExit("expected 4032 numbers, found %d" % len(nums))

header = """# Palm-detection anchor table, 2016 rows x (cx, cy).
#
# TRANSCRIBED VERBATIM from the official opencv_zoo reference literal
#   https://github.com/opencv/opencv_zoo  models/palm_detection_mediapipe/mp_palmdet.py
#   def _load_anchors(self)  -> np.array([...], dtype=np.float32)
#
# This file is deliberately NOT generated by the 2-layer formula that
# src/ai/hand_decode.cpp implements - it is the independent copy that the
# formula is checked against (tests/hand_detector_tests.cpp,
# hand_palm_anchor_table). Regenerating it from the formula would make the test
# unable to detect a wrong formula.
#
# Layout the formula must reproduce exactly:
#   indices    0 .. 1151   grid 24x24 (stride  8), 2 anchors per cell
#   indices 1152 .. 2015   grid 12x12 (stride 16), 6 anchors per cell
#   both blocks loop       for y -> for x -> for k
#   centre                 ((x + 0.5) / grid, (y + 0.5) / grid)
#
# Format: one "cx cy" pair per line, %.10g, in float32.
"""

with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(header)
    for i in range(2016):
        cx, cy = nums[2 * i], nums[2 * i + 1]
        f.write("%.10g %.10g\n" % (float(cx), float(cy)))

print("wrote %s: 2016 anchors" % out_path)
